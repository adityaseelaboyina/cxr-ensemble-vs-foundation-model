# All paired comparisons. Each analysis is one Holm family; the same (a, b) pair listed twice counts once.
FAM = {'base5': 'A', 'fm_evaxrecipe': 'B', 'same': 'C', 'fm_shared': 'D', 'full': 'E'}
INV = []
for an in ['base5', 'fm_evaxrecipe', 'fm_shared', 'same', 'full']:
    seen, fam_rows = set(), []
    for c in A[an]['primary_comparisons']:
        if (c['a'], c['b']) in seen:
            continue
        seen.add((c['a'], c['b']))
        fam_rows.append(dict(c, analysis=an, family=FAM[an], p_raw=p_add1(c['auroc_p'], an)))
    assert len(fam_rows) == A[an]['n_hypotheses'], (an, len(fam_rows), A[an]['n_hypotheses'])
    for r, h in zip(fam_rows, holm([r['p_raw'] for r in fam_rows])):
        r['p_holm_fam'] = h
    INV += fam_rows

# sensitivity only: normal-approximation p from the bootstrap SE, Holm across all comparisons
for r in INV:
    se = (r['auroc_ci'][1] - r['auroc_ci'][0]) / (2 * 1.959964)
    r['p_norm'] = 2 * (1 - NormalDist().cdf(abs(r['auroc_delta']) / se)) if se > 0 else 1.0
for r, h in zip(INV, holm([r['p_norm'] for r in INV])):
    r['p_holm_all'] = h


def comp(an, cid):
    c = next(c for c in A[an]['primary_comparisons'] if c['id'] == cid)
    r = next(r for r in INV if r['analysis'] == an and (r['a'], r['b']) == (c['a'], c['b']))
    return dict(c, p_holm_fam=r['p_holm_fam'])


